#!/usr/bin/env python3
"""Disclosure audit — authorship-policy §7. Computed from provenance.yaml, never hand-set.

  disclosure.py <book>                   print the audit
  disclosure.py <book> --update-listing  also rewrite the block between the disclosure
                                         markers in <book>/publishing/kdp-listing.md

An AUDIT tool, not a way to change authorship: it reads provenance and never writes it.
Text status is None only when every registered non-Scripture unit is human or public-domain
and nothing is empty, unregistered or unresolved.
"""
import sys, os, yaml, datetime
from collections import Counter
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bookarg import book_dir
import textunits

BOOK = book_dir()
prov = yaml.safe_load(open(f"{BOOK}/provenance.yaml"))
units = textunits.units(BOOK)
reg = textunits.registry(BOOK)

ai, unresolved, human, pd = [], [], [], []
for u in units:
    r = reg.get(u["id"])
    if r is None or u["text"] is None or r.get("sha") != textunits.sha(u["text"]) \
            or r.get("author") not in textunits.AUTHORS:
        unresolved.append(u["id"])
    elif r["author"] == "ai-drafted":
        ai.append(u["id"])
    elif r["author"] == "public-domain":
        pd.append(u["id"])
    else:
        human.append(u["id"])

if ai:
    text_status = f"AI-GENERATED / AI-DRAFTED TEXT REMAINS — {len(ai)} unit(s)"
elif unresolved:
    text_status = f"UNRESOLVED — {len(unresolved)} unit(s) have no settled author; cannot compute"
else:
    text_status = "None"

kinds = Counter(next(u["kind"] for u in units if u["id"] == i) for i in ai)
img = prov.get("images", {})
fmt = lambda v: v if isinstance(v, str) else f"{v.get('source')}; editing {v.get('editing')}"
lines = [
    f"Disclosure audit — {os.path.basename(BOOK)}  ({datetime.date.today().isoformat()}, "
    f"from provenance.yaml)",
    "",
    f"TEXT: {text_status}",
    f"  {len(units)} units: human {len(human)} · public-domain {len(pd)} · "
    f"ai-drafted {len(ai)} · unresolved/empty {len(unresolved)}",
]
if ai:
    lines.append("  ai-drafted by kind: " + ", ".join(f"{k} {n}" for k, n in kinds.most_common()))
if unresolved:
    lines.append("  unresolved/empty: " + ", ".join(unresolved))
lines += [
    f"IMAGES — interior: {fmt(img.get('interior', 'not recorded'))}",
    f"IMAGES — cover: {fmt(img.get('cover', 'not recorded'))}",
    f"TRANSLATIONS: {prov.get('translation', 'not recorded')}",
]
report = "\n".join(lines)
print(report)

if "--update-listing" in sys.argv:
    path = f"{BOOK}/publishing/kdp-listing.md"
    s = open(path).read()
    a, b = "<!-- disclosure:begin -->", "<!-- disclosure:end -->"
    if a not in s or b not in s:
        sys.exit(f"{path}: disclosure markers missing")
    block = (f"{a}\n_Generated by `scripts/disclosure.py {os.path.basename(BOOK)} --update-listing` "
             f"— do not edit by hand. Answer KDP's AI-content questions from this audit, and "
             f"re-run it after any text or image change._\n\n```\n{report}\n```\n{b}")
    s = s[:s.index(a)] + block + s[s.index(b) + len(b):]
    open(path, "w").write(s)
    print(f"\n  updated {path}")
